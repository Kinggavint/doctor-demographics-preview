"""Generate the CloudFront viewer-request function for doctordemographics.com.

usage (from repo root):  python3 cloudfront/gen_fn.py
inputs:  REDIRECTS.csv                       (rows written by build/gen.py; PR #3 style)
         cloudfront/old-wp-404-redirects.csv (old WordPress URLs that 404, audit 2026-11-04)
output:  cloudfront/apex-site-doctor-demographics-redirects.js, cloudfront/redirect-map.json

Same function as the one LIVE since Oct 30 (apex-site-doctor-demographics-redirects, ETag ETVPDKIKX0DER,
generated by the box copy of this script). New here: the old-WP rows, and a short prefix rule list so the
function stays under the 10 KB CloudFront Functions size limit. An exact row always wins over a prefix rule.
A prefix rule may never match a page that exists on the site (checked by cloudfront/test_fn.js against dist/).
"""
import csv, json, os, re
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(HERE)
LIVE = 'https://doctordemographics.com'; ORDER = 'https://order.doctordemographics.com'
# GHL pages that move to the order subdomain (same list as build/gen.py GHL_PATHS). Unchanged.
GHL = ['/getsocial', '/accessdso', '/apexchat', '/ppschedule', '/best-sites-report-form', '/comp-report-form', '/quick-view-report-form',
       '/site-viabilty-report-form', '/best-sites-report-order', '/comp-report-order', '/marketing-report-order', '/quick-view-report-order',
       '/site-viability-order', '/telephone-consultation-order', '/order-complete', '/order-complete-telephone']
# Prefix fallbacks for old WordPress sections. NEVER add a prefix that has live pages (e.g. /blog/b/).
PREFIX = [('/podcasts/', '/podcast/'), ('/category/podcasts/', '/podcast/'),
          ('/blog/page/', '/blog/'), ('/blog-2/', '/blog/'), ('/tag/', '/blog/'), ('/category/', '/blog/'), ('/author/', '/blog/'),
          ('/newsletter/', '/blog/'), ('/videos/', '/blog/'),
          ('/product-category/', '/reports/'), ('/product/', '/reports/'), ('/webinar/', '/reports/'),
          ('/portfolio/', '/reports/'), ('/case-studies/', '/reports/'), ('/my-account/', '/reports/'), ('/shop/', '/reports/'),
          ('/team/', '/about/'), ('/marketing/', '/marketing-report/')]
YEAR = '/blog/'  # /2015/, /2019/04/, /2016/page/2/ ...  (^/(19|20)\d\d/)

def norm(p): p = p.lower().rstrip('/'); return p or '/'
def final(t):
    if t.startswith(LIVE): t = t[len(LIVE):] or '/'
    if t.startswith('http'): return t
    k = norm(t)
    if k in GHL: return ORDER + k
    return '/' if k == '/' else k + '/'
def by_rule(k):
    s = k + '/'
    for pre, t in PREFIX:
        if s.startswith(pre): return t
    if re.match(r'^/(19|20)\d\d/', s): return YEAR
    return None

M = {}
def add(src, dst, where):
    k = norm(src); t = final(dst)
    if k in M and M[k] != t: raise SystemExit(f'conflict for {k}: {M[k]} vs {t} ({where})')
    M[k] = t
for r in csv.DictReader(open(os.path.join(ROOT, 'REDIRECTS.csv'))):
    assert r['type'] == '301', r; add(r['from'], r['to'], 'REDIRECTS.csv')
for g in GHL: M.setdefault(g, ORDER + g)
OLD = list(csv.DictReader(open(os.path.join(HERE, 'old-wp-404-redirects.csv'))))
for r in OLD:
    add(r['old_url'], r['target'], 'old-wp-404-redirects.csv')
full = dict(M)
# drop rows the prefix rules already cover (keeps the function small); REDIRECTS.csv/GHL rows always stay explicit
keep_explicit = {norm(r['from']) for r in csv.DictReader(open(os.path.join(ROOT, 'REDIRECTS.csv')))} | set(GHL)
E = {k: v for k, v in M.items() if k in keep_explicit or by_rule(k) != v}
for t in list(E.values()) + [t for _, t in PREFIX] + [YEAR]:
    assert t.startswith(ORDER) or t.startswith('/'), t
T = sorted(set(E.values()) | {t for _, t in PREFIX} | {YEAR}); ti = {t: i for i, t in enumerate(T)}
P = '[' + ','.join('[%s,%d]' % (json.dumps(p), ti[t]) for p, t in PREFIX) + ']'
js = '''var T=%s;
var M=%s;
var P=%s;var Y=%d;
var A='https://doctordemographics.com';
function qs(q){var p=[];for(var k in q){var v=q[k];if(v.multiValue){for(var i=0;i<v.multiValue.length;i++)p.push(k+(v.multiValue[i].value!==''?'='+v.multiValue[i].value:''));}else p.push(k+(v.value!==''?'='+v.value:''));}return p.length?'?'+p.join('&'):'';}
function r301(loc){return{statusCode:301,statusDescription:'Moved Permanently',headers:{location:{value:loc},'cache-control':{value:'max-age=3600'}}};}
function pre(k){var s=k+'/';for(var j=0;j<P.length;j++){if(s.indexOf(P[j][0])===0)return P[j][1];}if(/^\\/(19|20)\\d\\d\\//.test(s))return Y;return undefined;}
function handler(event){
var req=event.request;var h=(req.headers.host&&req.headers.host.value||'').toLowerCase();
var www=h==='www.doctordemographics.com';var B=(www||h==='doctordemographics.com')?A:'';
var u=req.uri;var k=u.toLowerCase().replace(/\\/+$/,'')||'/';var q=qs(req.querystring);
var i=M[k];if(i===undefined)i=pre(k);
if(i!==undefined){var t=T[i];return r301((t.charAt(0)==='/'?B:'')+t+q);}
var last=u.slice(u.lastIndexOf('/')+1);var file=last.indexOf('.')>=0;
if(!file&&u!==u.toLowerCase()){var l=u.toLowerCase();return r301(B+l+(l.slice(-1)==='/'?'':'/')+q);}
if(!file&&u.slice(-1)!=='/'){return r301(B+u+'/'+q);}
if(www){return r301(A+u+q);}
if(u.slice(-1)==='/'){req.uri=u+'index.html';}
return req;}
''' % (json.dumps(T, separators=(',', ':')), '{' + ','.join(json.dumps(k) + ':' + str(ti[v]) for k, v in E.items()) + '}', P, ti[YEAR])
open(os.path.join(HERE, 'apex-site-doctor-demographics-redirects.js'), 'w').write(js)
json.dump(full, open(os.path.join(HERE, 'redirect-map.json'), 'w'), indent=1)
n = len(js.encode())
print(n, 'bytes (limit 10240)', len(full), 'redirects', len(E), 'explicit', len(PREFIX) + 1, 'prefix rules', len(T), 'targets')
assert n < 10240, 'over the CloudFront Functions 10 KB limit'
