#!/usr/bin/env bash
# Apex proof verifier. Usage: verify.sh <dir> [base_url]
set -u
DIR="${1:?usage: verify.sh <dir> [base_url]}"; BASE="${2:-}"
cd "$DIR" || exit 2
FAIL=0
report(){ if [ "$2" = 0 ]; then echo "PASS  $1"; else echo "FAIL  $1"; FAIL=1; fi; }
mapfile -t PAGES < <(find . -name '*.html' -not -path './build/*' -not -path './.git/*' | sort)
echo "Checking ${#PAGES[@]} pages in $(pwd)"
# a noindex
bad=0; for p in "${PAGES[@]}"; do grep -qiE '<meta[^>]+name="robots"[^>]+noindex, ?nofollow' "$p" || { echo "  missing noindex,nofollow: $p"; bad=1; }; done
report "(a) noindex,nofollow on every page" $bad
# b robots
bad=0; grep -qE '^Disallow: /\s*$' robots.txt 2>/dev/null || { echo "  robots.txt missing Disallow: /"; bad=1; }
report "(b) robots.txt Disallow: /" $bad
# c copy lint + d links via python
python3 - "${PAGES[@]}" <<'PY'
import sys,re,os,html
from html.parser import HTMLParser
class P(HTMLParser):
    def __init__(s):
        super().__init__(); s.t=[]; s.skip=0; s.refs=[]
    def handle_starttag(s,tag,a):
        a=dict(a)
        if tag in('script','style'): s.skip+=1
        for k in('href','src'):
            v=a.get(k)
            if v and not re.match(r'^(https?:|mailto:|tel:|#|data:|javascript:|//)',v): s.refs.append(v)
        for k in('alt','title','placeholder','aria-label'):
            if a.get(k): s.t.append(a[k])
        if tag=='meta' and a.get('name') in('description',) and a.get('content'): s.t.append(a['content'])
    def handle_endtag(s,tag):
        if tag in('script','style'): s.skip-=1
    def handle_data(s,d):
        if not s.skip: s.t.append(d)
emoji=re.compile('[\U0001F300-\U0001FAFF\u2600-\u27BF\U0001F000-\U0001F2FF\uFE0F]')
rules=[('dash (en/em)',re.compile('[\u2013\u2014]')),('spaced hyphen dash',re.compile(r'\S\s-\s\S')),
 ('emoji',emoji),("word 'free'",re.compile(r'\bfree\b',re.I)),
 ('agent attribution',re.compile(r'\b(grok|chatgpt|openai|claude|ai[- ]generated|generated by ai|built by ai)\b',re.I))]
copy=links=0
for p in sys.argv[1:]:
    x=P(); x.feed(open(p,encoding='utf-8').read())
    for chunk in x.t:
        line=' '.join(chunk.split())
        for n,r in rules:
            if r.search(line): print(f"  COPY {p}: {n}: \"{line[:110]}\""); copy=1
    for ref in x.refs:
        f=ref.split('#')[0].split('?')[0]
        if not f: continue
        t=os.path.normpath(os.path.join(os.path.dirname(p),html.unescape(f)))
        if f.endswith('/'): t=os.path.join(t,'index.html')
        if not os.path.exists(t): print(f"  BROKEN {p}: {ref}"); links=1
open('/tmp/.verify_py','w').write(f"{copy} {links}")
PY
read c l < /tmp/.verify_py
report "(c) copy lint (dashes, emojis, 'free', attribution)" $c
report "(d) relative links and images resolve" $l
# e remote
if [ -n "$BASE" ]; then
  bad=0; BASE="${BASE%/}"
  for p in "${PAGES[@]}" robots.txt; do u="$BASE/${p#./}"
    code=$(curl -s -o /tmp/.vpage -w '%{http_code}' "$u")
    [ "$code" = 200 ] || { echo "  $code $u"; bad=1; continue; }
    case "$p" in *.html) grep -qi 'noindex' /tmp/.vpage || { echo "  no noindex live: $u"; bad=1; };; esac
  done
  report "(e) live pages 200 + noindex at $BASE" $bad
else echo "SKIP  (e) no base URL given"; fi
[ $FAIL = 0 ] && echo "RESULT: PASS" || echo "RESULT: FAIL"
exit $FAIL
